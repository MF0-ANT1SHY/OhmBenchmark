#!/usr/bin/env python3
"""Generate the per-case re-run plan from the case specs, so it cannot drift.

Objective (4) allows a documented, reproducible re-run plan where device time is unavailable.
Writing that by hand would rot the moment a commit moved, so it is generated from
`cases/*/case.json` plus what the repository actually holds: which harness patch exists, which
instrumenter exists, and which host clone is present.

Every row states the exact command to run and what the declared metric is, so the next attempt
starts from facts rather than from this session's narration.
"""
import json
import re
from pathlib import Path

REPO = Path('/home/research/OhmBenchmark-main')
OUT = REPO / 'docs' / 'analysis' / 'rerun-plan.md'

# which instrumenter serves which case, where one exists
INSTRUMENTERS = {
    'browser_insert_date_lookup_cache': 'tools/instrument_statement_count.py',
    'sheafreader_unread_counts_n_plus_1': 'tools/instrument_query_count.py',
    'interviewapp_search_history_sync_flush': 'tools/instrument_flush_count.py',
    'interviewapp_search_history_unbounded': 'result:history_entries_and_render_cost',
    'ytmusic_history_json_parse_per_row': 'self-installing:tools/instrument_ytmusic.py',
    'ytmusic_search_no_debounce': 'self-installing:tools/instrument_ytmusic.py',
    'ytmusic_current_playing_timeupdate': 'self-installing:tools/instrument_ytmusic.py',
}
# cases whose declared count is read from the app's own diag log
DIAG_SOURCE = {'ytmusic_history_json_parse_per_row': 'diag:parseTotal'}

# reconstructed SHAs, when the recorded ones do not resolve (git am rewrote them)
RECONSTRUCTED = {
    'ytmusic_history_json_parse_per_row': ('627611f', '157104d'),
    'ytmusic_search_no_debounce': ('157104d', 'c4b1879'),
    'ytmusic_current_playing_timeupdate': ('c4b1879', 'e175817'),
}

# status from the coverage report
import subprocess
# the report writes JSON to a file when given a path; its stdout is a human summary
subprocess.run(['python3', 'tools/report_oracle_coverage.py', '--json', '/tmp/covgen.json'],
               cwd=REPO, capture_output=True, text=True)
verdicts = {}
try:
    cov = json.loads(Path('/tmp/covgen.json').read_text(encoding='utf-8'))
    for r in cov.get('cases', []):
        verdicts[r['case']] = r
except Exception as exc:
    print(f'  WARNING: could not read the coverage report ({exc}); verdicts will be "?"')

rows = []
for spec_path in sorted((REPO / 'cases').glob('*/case.json')):
    case = spec_path.parent.name
    spec = json.loads(spec_path.read_text(encoding='utf-8'))
    v = verdicts.get(case, {})
    verdict = v.get('verdict', '?')
    if verdict not in ('never-run', 'collected-not-used', 'proxy', 'mechanism-absent'):
        continue
    host = spec['host_app'].get('host', '')
    local = Path(spec['host_app'].get('local_path', '') or '')
    unfixed = RECONSTRUCTED.get(case, (spec.get('unfixed_commit'), spec.get('fixed_commit')))[0]
    fixed = RECONSTRUCTED.get(case, (spec.get('unfixed_commit'), spec.get('fixed_commit')))[1]
    patch_dir = REPO / 'device-tests' / 'patches' / case
    has_patch = patch_dir.exists()
    instr = INSTRUMENTERS.get(case)
    rows.append({
        'case': case, 'verdict': verdict, 'metric': spec['test_oracle']['metric'],
        'primitive': v.get('primitive', ''), 'host': host,
        'host_present': local.exists() if str(local) else False,
        'unfixed': unfixed, 'fixed': fixed, 'has_patch': has_patch, 'instrumenter': instr,
        'diag': DIAG_SOURCE.get(case),
    })

lines = ['# Re-run plan for the cases that are not yet measured', '',
         'Generated by `tools/build_rerun_plan.py` from `cases/*/case.json` and the state of the',
         'repository, so it cannot drift from the specs. Run it again after any change:', '',
         '```bash', 'python3 tools/build_rerun_plan.py', '```', '',
         'Each row gives the exact command. `unfixed`/`fixed` are the commits to build; for',
         'ytmusic they are the *reconstructed* SHAs, because `git am` rewrote the recorded ones',
         'and only trees are stable (`hosts_patches/REPRODUCE.md`).', '',
         f'**{len(rows)} cases outstanding.**', '',
         '## What each case needs', '',
         '| case | verdict | declared metric | host | harness patch | instrumenter |',
         '| --- | --- | --- | --- | --- | --- |']
for r in rows:
    instr = r['instrumenter'] or ('**missing**' if r['has_patch'] else '**missing**')
    lines.append(f"| `{r['case']}` | {r['verdict']} | {r['metric']} | "
                 f"{'ok' if r['host_present'] else '**no clone**'} | "
                 f"{'yes' if r['has_patch'] else 'no'} | {instr} |")

lines += ['', '## Exact commands', '',
          'For a case with a harness patch and an instrumenter:', '', '```bash',
          'cd /home/research/OhmBenchmark-main',
          'bash device-tests/run_declared_metric.sh <case> <host> <unfixed> <fixed> <instrumenter> 3',
          '```', '',
          'For a host with no harness patch (the tool installs it):', '', '```bash',
          'bash device-tests/run_declared_metric.sh <case> <host> <unfixed> <fixed> \\',
          '     self-installing:<tool> 3', '```', '',
          'When the declared count is read from the app diag log, add the source:', '', '```bash',
          'SUMMARY_SOURCE=diag:<key> bash device-tests/run_declared_metric.sh ...', '```', '']

need_instrumenter = [r['case'] for r in rows if not r['instrumenter']]
need_patch = [r['case'] for r in rows if not r['has_patch'] and not r['instrumenter']]
no_clone = [r['case'] for r in rows if not r['host_present']]

lines += ['## Work remaining, by category', '']
lines.append(f'- **needs an instrumenter written**: {len(need_instrumenter)} cases')
for c in need_instrumenter:
    lines.append(f'  - `{c}`')
lines.append(f'- **needs a harness built before anything else**: {len(need_patch)} cases')
for c in need_patch:
    lines.append(f'  - `{c}`')
lines.append(f'- **host clone missing**: {len(no_clone)} cases')
for c in no_clone:
    lines.append(f'  - `{c}`')
lines += ['', '## Device notes', '',
          '- the driver reports and enforces every step; a failure names itself',
          '- `device-tests/host_module.py CASE [--ability]` resolves the module and ability the',
          '  device expects, verified for all four hosts used so far',
          '- hosts install under different module directories: interviewapp `phone`,',
          '  weatherassistant `alatus`, the rest `entry`',
          '- if a bench entry is missing, `device-tests/harness/` now holds reusable templates',
          '  (`OhmProbe.ets`, `Diag.ets`) and `tools/instrument_ytmusic.py` shows how to install',
          '  them and hook `EntryAbility.onNewWant`',
          '- a counter must be placed where the measured code actually runs: three separate',
          '  attempts on the ytmusic history case read 0 because the counter sat on a path the',
          '  bench never exercised, and the same trap produced "unfixed 1000, fixed 0" on the',
          '  flush case before the marker was moved after the deferred-flush wait',
          '']

OUT.write_text('\n'.join(lines), encoding='utf-8')
print(f'  wrote {OUT.relative_to(REPO)}: {len(rows)} cases, '
      f'{len(need_instrumenter)} need an instrumenter, {len(no_clone)} have no clone')
